"use strict";

/**
 * build-skills — generate agent skill trees from `skills-src/`.
 *
 * Skills reference docs by markdown link, authored relative to the source file in
 * `skills-src/<name>/`. Links that leave the skill are rewritten relative to each
 * generated copy, and the build fails on a link that does not resolve to a file.
 * The manifest records each skill's linked files and a `context_hash` that
 * changes whenever the skill, its bundled files, or a linked doc changes.
 *
 * The same generated tree is mirrored into every agent skill root that follows the
 * open Agent Skills standard: `.github/skills/` (Copilot) and `.claude/skills/`
 * (Claude Code).
 *
 * Resolution, normalization, and hashing live in `scripts/skill-resolver.js`; this
 * script is a thin wrapper that walks `skills-src/`, writes the target trees, emits
 * a gitignored `manifest.json` for later phases, and enforces the pre-commit gate.
 * It imports the resolver — it never redefines `normalize`/`resolve`/`context_hash`.
 */

const fs = require("fs");
const path = require("path");

const {
  BuildError,
  resolveSkill,
  relinkOutbound,
  relativeLinks,
  contextHash,
  listFiles,
  sha256Hex,
} = require("./skill-resolver");

const REPO_ROOT = path.join(__dirname, "..");
const SRC_DIR = path.join(REPO_ROOT, "skills-src");

// Every agent skill root that follows the open Agent Skills standard. The same
// generated tree is written to each so Copilot and Claude Code see the
// identical, self-contained skills built from `skills-src/`.
const OUT_DIRS = [
  path.join(REPO_ROOT, ".github", "skills"),
  path.join(REPO_ROOT, ".claude", "skills"),
];

function toRepoRelative(absPath) {
  return path.relative(REPO_ROOT, absPath).split(path.sep).join("/");
}

// The generated `.github/skills/` tree is a runtime artifact: only the skill
// files the agent reads at trigger time belong there. Eval assets (`evals/`)
// and eval sandbox dirs (`*-workspace/`) are dev/test-only, consumed by the
// eval runner from `skills-src/` directly — copying them into the
// build would duplicate them and let a triggered skill read its own answer key.
function isRuntimeSkillFile(relPath) {
  const firstSegment = relPath.split("/")[0];
  return firstSegment !== "evals" && !firstSegment.endsWith("-workspace");
}

// Thin adapter kept for callers (and tests) that want the generated bytes only.
function buildSkill({ srcText, skillName }) {
  return resolveSkill({ srcText, skillName }).generated;
}

function writeIfChanged(absPath, contents) {
  const buf = Buffer.isBuffer(contents)
    ? contents
    : Buffer.from(contents, "utf8");
  if (fs.existsSync(absPath) && fs.readFileSync(absPath).equals(buf)) {
    return false;
  }
  fs.mkdirSync(path.dirname(absPath), { recursive: true });
  fs.writeFileSync(absPath, buf);
  return true;
}

// Removes empty directories left behind after a stale file is deleted, walking
// bottom-up so a directory that becomes empty after its children are pruned is
// itself removed.
function pruneEmptyDirs(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) pruneEmptyDirs(path.join(dir, entry.name));
  }
  if (fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
}

// Bytes for one runtime file of a skill copied to `skillOutDir`, with markdown
// links that leave the skill rewritten relative to the copy.
function renderFile({ skillName, skillSrcDir }, rel, skillOutDir) {
  const srcFile = path.join(skillSrcDir, rel);
  const linkTo = relativeLinks(skillOutDir);
  if (rel === "SKILL.md") {
    const { generated } = resolveSkill({
      srcText: fs.readFileSync(srcFile, "utf8"),
      skillName,
      skillDir: skillSrcDir,
      linkTo,
    });
    return Buffer.from(generated, "utf8");
  }
  if (rel.endsWith(".md")) {
    const text = fs.readFileSync(srcFile, "utf8");
    return Buffer.from(relinkOutbound(text, rel, skillSrcDir, linkTo), "utf8");
  }
  return fs.readFileSync(srcFile);
}

// Sync every skill into a single output root: write changed files, prune stale
// files/dirs left over from removed sources, and drop skill directories whose
// source is gone. Returns per-target change counts.
function syncTarget(outDir, builtSkills, expectedSkillNames, manifestBytes) {
  let changed = 0;
  let removed = 0;

  for (const skill of builtSkills) {
    const { skillName, expectedRel } = skill;
    const skillOutDir = path.join(outDir, skillName);

    for (const rel of expectedRel) {
      const bytes = renderFile(skill, rel, skillOutDir);
      if (writeIfChanged(path.join(skillOutDir, rel), bytes)) changed += 1;
    }

    // Delete previously generated files that no longer have a source
    // counterpart (e.g. a file removed from skills-src).
    if (fs.existsSync(skillOutDir)) {
      for (const rel of listFiles(skillOutDir)) {
        if (!expectedRel.has(rel)) {
          fs.rmSync(path.join(skillOutDir, rel));
          removed += 1;
        }
      }
      pruneEmptyDirs(skillOutDir);
    }
  }

  // Delete generated skill directories whose source has been deleted entirely.
  if (fs.existsSync(outDir)) {
    for (const entry of fs.readdirSync(outDir, { withFileTypes: true })) {
      if (entry.isDirectory() && !expectedSkillNames.has(entry.name)) {
        fs.rmSync(path.join(outDir, entry.name), {
          recursive: true,
          force: true,
        });
        removed += 1;
      }
    }
  }

  if (writeIfChanged(path.join(outDir, "manifest.json"), manifestBytes)) {
    changed += 1;
  }

  return { changed, removed };
}

function run({ srcDir = SRC_DIR, outDir, outDirs, log = () => {} } = {}) {
  if (!fs.existsSync(srcDir)) {
    throw new BuildError(
      `Skill source directory not found: ${toRepoRelative(srcDir)}`,
    );
  }

  // Back-compat: a single `outDir` overrides the default multi-target set.
  const targets = outDirs ?? (outDir ? [outDir] : OUT_DIRS);

  const skillNames = fs
    .readdirSync(srcDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b));

  // Resolve every skill before writing anything, so a resolution error leaves
  // all targets untouched.
  const manifest = {};
  const builtSkills = skillNames.map((skillName) => {
    const skillSrcDir = path.join(srcDir, skillName);
    const expectedRel = [
      ...new Set(listFiles(skillSrcDir).filter(isRuntimeSkillFile)),
    ].sort((a, b) => a.localeCompare(b));

    const skillMdPath = path.join(skillSrcDir, "SKILL.md");
    if (expectedRel.includes("SKILL.md")) {
      const resolved = resolveSkill({
        srcText: fs.readFileSync(skillMdPath, "utf8"),
        skillName,
        skillDir: skillSrcDir,
      });
      manifest[skillName] = {
        context_hash: resolved.context_hash,
        links: resolved.links,
        source_sha: `sha256:${sha256Hex(fs.readFileSync(skillMdPath))}`,
      };
    }

    return {
      skillName,
      skillSrcDir,
      expectedRel: new Set(expectedRel),
    };
  });

  const manifestBytes = Buffer.from(
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
  const expectedSkillNames = new Set(skillNames);

  let changed = 0;
  let removed = 0;
  for (const target of targets) {
    const result = syncTarget(
      target,
      builtSkills,
      expectedSkillNames,
      manifestBytes,
    );
    changed += result.changed;
    removed += result.removed;
  }

  log(
    `build-skills: ${skillNames.length} skill(s) processed into ${targets.length} target(s), ${changed} file(s) written, ${removed} file(s)/dir(s) removed.`,
  );
  return { built: skillNames.length, changed, removed };
}

module.exports = {
  BuildError,
  buildSkill,
  contextHash,
  run,
};

if (require.main === module) {
  try {
    run({ log: (msg) => process.stdout.write(`${msg}\n`) });
  } catch (err) {
    if (err instanceof BuildError) {
      process.stderr.write(`\nbuild-skills failed: ${err.message}\n`);
      process.exit(1);
    }
    throw err;
  }
}
